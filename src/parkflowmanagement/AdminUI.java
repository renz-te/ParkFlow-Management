    private void purgeHistoryBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_purgeHistoryBtnActionPerformed
        // 1. Retention Parameter Extraction
        String retentionText = configRetentionField.getText().trim();
        if (retentionText.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Data Retention parameter is not defined.", "Execution Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }

        int retentionDays;
        try {
            retentionDays = Integer.parseInt(retentionText);
        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Invalid retention value. Must be a whole number.", "Data Type Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }

        // 2. Administrator Confirmation
        int confirm = javax.swing.JOptionPane.showConfirmDialog(this,
            "WARNING: This will permanently delete all vehicle history records older than " + retentionDays + " days.\nThis action cannot be undone. Proceed?",
            "Confirm Data Purge",
            javax.swing.JOptionPane.YES_NO_OPTION,
            javax.swing.JOptionPane.WARNING_MESSAGE);

        if (confirm != javax.swing.JOptionPane.YES_OPTION) {
            return; // Execution halted by administrator
        }

        // 3. Cutoff Date Calculation
        java.util.Calendar cal = java.util.Calendar.getInstance();
        cal.add(java.util.Calendar.DAY_OF_YEAR, -retentionDays);
        String cutoffDate = new java.text.SimpleDateFormat("yyyy-MM-dd 00:00:00").format(cal.getTime());

        // 4. Database Execution
        java.sql.Connection conn = null;
        java.sql.PreparedStatement pstmt = null;

        try {
            conn = DatabaseUtil.getConnection();
            String sql = "DELETE FROM vehicle_history WHERE entry_time < ?";
            pstmt = conn.prepareStatement(sql);
            pstmt.setString(1, cutoffDate);

            int rowsAffected = pstmt.executeUpdate();

            javax.swing.JOptionPane.showMessageDialog(this, "History purge complete.\nObsolete records deleted: " + rowsAffected, "System Notification", javax.swing.JOptionPane.INFORMATION_MESSAGE);

        } catch (java.sql.SQLException e) {
            e.printStackTrace();
            javax.swing.JOptionPane.showMessageDialog(this, "Database error during purge operation.", "Execution Failure", javax.swing.JOptionPane.ERROR_MESSAGE);
        } finally {
            try {
                if (pstmt != null) pstmt.close();
                if (conn != null) conn.close();
            } catch (java.sql.SQLException ex) { ex.printStackTrace(); }
        }
        // TODO add your handling code here:
    }//GEN-LAST:event_purgeHistoryBtnActionPerformed

