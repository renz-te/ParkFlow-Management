    userContactField.setText(model.getValueAt(modelRow, 4).toString());
    userRoleComboBox.setSelectedItem(model.getValueAt(modelRow, 5).toString());

    String currentStatus = model.getValueAt(modelRow, 6).toString();
    userStatusComboBox.setSelectedItem(currentStatus);

